import { test, expect } from "@playwright/test";
import { fileURLToPath } from "node:url";

test("mixed paper has working figures, status navigation, offline recovery and a released review", async ({page, context}) => {
  const external = [], errors = [];
  page.on("request", request => { if (/supabase\.co|razorpay\.com/.test(request.url()) || request.method() === "POST") external.push(request.url()); });
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/portal-preview/paper");
  const number = page.getByLabel("Your numerical answer");
  await expect(page.getByRole("img",{name:/Nine square tiles/})).toBeVisible();
  await number.fill("9");
  await page.getByRole("button",{name:"Save answer",exact:true}).press("Enter");
  await expect(page.getByText("Sample answers saved in this tab.",{exact:true})).toBeVisible();
  await page.reload();
  await expect(number).toHaveValue("9");
  await page.getByRole("button",{name:"Mark for review",exact:true}).press("Enter");
  await page.getByLabel("Show questions").selectOption("marked");
  const nav = page.getByRole("complementary",{name:"Question navigator"});
  await expect(nav.getByRole("button",{name:/Go to question/})).toHaveCount(1);
  await page.getByRole("navigation",{name:"Sections",exact:true}).getByRole("button",{name:/MSQ/}).press("Enter");
  await context.setOffline(true);
  await page.getByRole("button",{name:/A The circle has the same diameter/}).click();
  await expect(page.getByText("Answers saved on this device. Waiting to sync.",{exact:true})).toBeVisible();
  await context.setOffline(false);
  await expect(page.getByText("Sample answers saved in this tab.",{exact:true})).toBeVisible();
  await page.getByRole("navigation",{name:"Sections",exact:true}).getByRole("button",{name:/MCQ/}).press("Enter");
  await page.getByRole("button",{name:/A Above and to the left/}).click();
  await nav.getByRole("button",{name:"Submit attempt"}).click();
  const dialog = page.getByRole("dialog");
  await expect(dialog).toContainText("3 of 6 answered");
  await dialog.getByRole("button",{name:"Submit & view report"}).click();
  await expect(page.getByRole("group",{name:"Objective result"})).toContainText("4/24");
  await expect(page.getByRole("region",{name:"Attempt insights"})).toContainText("33%");
  await page.getByRole("button",{name:"Review partial credit questions (1)",exact:true}).press("Enter");
  await expect(page.getByRole("combobox",{name:"Result",exact:true})).toHaveValue("partial");
  await expect(page.getByRole("navigation",{name:"Review questions"}).getByRole("button")).toHaveCount(1);
  await expect(page.locator(".analysis-item")).toContainText("Correct answer A, C");
  await expect(page.locator(".analysis-item img")).toBeVisible();
  await page.getByRole("combobox",{name:"Question type",exact:true}).selectOption("nat");
  await expect(page.getByText("No questions match these filters.")).toBeVisible();
  await page.getByRole("combobox",{name:"Result",exact:true}).selectOption("correct");
  await expect(page.getByText("Three plus two plus four is nine.")).toHaveCount(0);
  await page.getByRole("button",{name:"View solution",exact:true}).click();
  await expect(page.locator(".analysis-item")).toContainText("Three plus two plus four is nine.");
  await page.addScriptTag({path:fileURLToPath(new URL("../../node_modules/axe-core/axe.min.js",import.meta.url))});
  expect(await page.evaluate(async()=>(await window.axe.run(".analysis-workspace",{runOnly:{type:"tag",values:["wcag2a","wcag2aa","wcag21aa"]}})).violations.map(item=>[item.id,item.nodes.map(node=>node.target)]))).toEqual([]);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize().width);
  await page.reload();
  await expect(page.getByRole("group",{name:"Objective result"})).toContainText("4/24");
  await page.getByRole("button",{name:"Start a fresh sample paper"}).click();
  await expect(number).toHaveValue("");
  await page.addScriptTag({path:fileURLToPath(new URL("../../node_modules/axe-core/axe.min.js",import.meta.url))});
  expect(await page.evaluate(async()=>(await window.axe.run(".attempt-workspace",{runOnly:{type:"tag",values:["wcag2a","wcag2aa","wcag21aa"]}})).violations.map(item=>[item.id,item.nodes.map(node=>node.target)]))).toEqual([]);
  expect(errors).toEqual([]);
  expect(external).toEqual([]);
});
